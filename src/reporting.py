"""
MEDSCOPE AI — Reporting Module
Generates human-readable text and CSV reports from evaluation results.
"""
from __future__ import annotations

import json
import logging
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional

import pandas as pd

from config.settings import REPORTS_DIR

logger = logging.getLogger(__name__)


def generate_text_report(
    task: str,
    eval_results: Dict[str, Dict],
    best_model_name: str,
    metadata: Dict[str, Any],
) -> Path:
    """Write a plain-text research summary report for the given task."""
    out_dir = REPORTS_DIR / task
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "research_report.txt"

    lines = [
        "=" * 70,
        f"MEDSCOPE AI — Research Report",
        f"Task: {task.replace('_', ' ').title()}",
        f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        "=" * 70,
        "",
        "DATASET",
        f"  Name       : {metadata.get('dataset', 'N/A')}",
        f"  Source     : {metadata.get('source', 'N/A')}",
        f"  Target     : {metadata.get('target_column', 'N/A')}",
        f"  Definition : {metadata.get('target_definition', 'N/A')}",
        f"  Train rows : {metadata.get('train_samples', 'N/A')}",
        f"  Test rows  : {metadata.get('test_samples', 'N/A')}",
        "",
        "SELECTED MODEL",
        f"  Algorithm  : {best_model_name}",
        f"  CV ROC-AUC : {metadata.get('cv_roc_auc', 'N/A')}",
        f"  Trained at : {metadata.get('trained_at', 'N/A')}",
        "",
        "MODEL EVALUATION RESULTS (held-out test set)",
        "-" * 50,
    ]

    for model_name, m in eval_results.items():
        marker = " ← SELECTED" if model_name == best_model_name else ""
        lines += [
            f"  {model_name}{marker}",
            f"    Accuracy    : {m.get('accuracy', 'N/A')}",
            f"    Precision   : {m.get('precision', 'N/A')}",
            f"    Recall      : {m.get('recall', 'N/A')}",
            f"    F1          : {m.get('f1', 'N/A')}",
            f"    Specificity : {m.get('specificity', 'N/A')}",
            f"    ROC-AUC     : {m.get('roc_auc', 'N/A')}",
            f"    CV AUC mean : {m.get('cv_score_mean', 'N/A')}",
            f"    Train time  : {m.get('train_time_s', 'N/A')} s",
            "",
        ]

    lines += [
        "LIMITATIONS",
        f"  {metadata.get('known_limitations', 'N/A')}",
        "",
        "RESPONSIBLE USE NOTICE",
        "  This report was generated by an educational ML prototype.",
        "  Results do not constitute a clinical diagnosis or medical advice.",
        "  Models have not been independently validated or clinically certified.",
        "=" * 70,
    ]

    path.write_text("\n".join(lines), encoding="utf-8")
    logger.info("Text report saved: %s", path)
    return path


def generate_data_quality_report(
    task: str,
    validation_report,
) -> Path:
    """Save the validation report as a JSON file."""
    out_dir = REPORTS_DIR / task
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "data_quality.json"

    data = {
        "task": validation_report.task,
        "passed": validation_report.passed,
        "errors": validation_report.errors,
        "warnings": validation_report.warnings,
        "info": {
            k: (v if not hasattr(v, "tolist") else v.tolist())
            for k, v in validation_report.info.items()
        },
        "generated_at": datetime.now().isoformat(),
    }
    path.write_text(json.dumps(data, indent=2, default=str), encoding="utf-8")
    logger.info("Data quality report saved: %s", path)
    return path
